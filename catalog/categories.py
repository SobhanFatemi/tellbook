"""Conservative category cleanup shared by imports and manual editing."""
import re

ALIASES = {
    'رمانهای خارجی': 'رمان خارجی',
    'رمانهای ایرانی': 'رمان ایرانی',
    'رمان های خارجی': 'رمان خارجی',
    'رمان های ایرانی': 'رمان ایرانی',
    'شعرخارجی': 'شعر خارجی',
    'نقدادبی': 'نقد ادبی',
    'سیاست وتاریخ': 'سیاست و تاریخ',
    'ادبیات وعلوم انسانی': 'ادبیات و علوم انسانی',
    'علوم اجتماعی وسیاسی': 'علوم اجتماعی و سیاسی',
    'روانشناسی وتربیتی': 'روانشناسی و تربیتی',
    'سرگذشتنامه وکتابشناسی': 'سرگذشتنامه و کتابشناسی',
    'اساطیر وفرهنگ': 'اساطیر و فرهنگ',
    'موسیقی وسینما': 'موسیقی و سینما',
}


def normalize_category(value):
    text = re.sub(r'\s+', ' ', str(value or '').translate(str.maketrans({'ي':'ی', 'ك':'ک', '\u200c':' '}))).strip()
    if re.fullmatch(r'(?:گروه\s*)?[0۰٠](?:\.0)?', text):
        return ''
    return ALIASES.get(text, text)
